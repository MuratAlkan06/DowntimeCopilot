"""Pure report generator: run dir -> report.json + report.md (docs/durability.md "Report"). Never hand-edit
either file; re-run this instead. Reads meta.json, server/c*.json and node/c*.json; no network, no clock.

  python -m tools.durability.report RUN_DIR
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path


def _pct(xs: list[float], q: float) -> float | None:
    if not xs:
        return None
    xs = sorted(xs)
    return round(xs[min(len(xs) - 1, int(round(q * (len(xs) - 1))))], 3)


def _load(run_dir: Path, side: str) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted((run_dir / side).glob("c[0-9][0-9][0-9].json"))]


def build(run_dir: Path) -> dict:
    meta = json.loads((run_dir / "meta.json").read_text()) if (run_dir / "meta.json").is_file() else {}
    out: dict = {"run_id": meta.get("run_id"), "master_seed": meta.get("master_seed"),
                 "sync_interval_s": meta.get("sync_interval_s"), "sides": {}}
    for side in ("server", "node"):
        cycles = _load(run_dir, side)
        if not cycles:
            continue
        faults = Counter(c["fault"] for c in cycles)
        viol: dict[str, int] = Counter()
        known: dict[str, int] = Counter()
        expected: dict[str, int] = Counter()
        drains: dict[str, list[float]] = defaultdict(list)
        failing = []
        for c in cycles:
            for k, v in c["violations"].items():
                viol[k] += len(v)
            for k, v in c["known_windows"].items():
                known[k] += len(v) if isinstance(v, list) else int(v)
            for k, v in c["expected_fail"].items():
                expected[k] += len(v)
            if c["violations"]:
                failing.append({"cycle": c["cycle"], "fault": c["fault"], "seed": c["seed"],
                                "violations": c["violations"]})
            d = (c.get("drain") or {}).get("drain_s")
            if d is not None and c["fault"] != "poison":  # poison stalls are excluded from I3
                drains[c["fault"]].append(d)
        lost = sum(viol[k] for k in ("lost_acked", "lost_mirror", "lost_queued"))
        dup = sum(n for k, n in viol.items() if k.startswith("dup_"))
        out["sides"][side] = {
            "cycles": len(cycles), "faults_injected": dict(sorted(faults.items())),
            "records_lost": lost, "records_duplicated": dup,
            "violations": dict(sorted(viol.items())), "known_windows": dict(sorted(known.items())),
            "expected_fail": dict(sorted(expected.items())),
            "not_mirrored": sum(c.get("reconcile", {}).get("not_mirrored_kv", 0) for c in cycles),
            "drain_s": {f: {"n": len(v), "p50": _pct(v, 0.5), "max": max(v)} for f, v in sorted(drains.items())},
            "stall_skipped_attempts": [c["stall"] for c in cycles if c.get("stall")],
            "failing_cycles": failing,
        }
    out["verdict"] = "PASS" if all(s["records_lost"] == 0 and s["records_duplicated"] == 0 and not s["violations"]
                                   for s in out["sides"].values()) else "FAIL"
    return out


def markdown(r: dict) -> str:
    lines = [f"# Durability report `{r['run_id']}`", "",
             "Generated by `python -m tools.durability.report` from the run directory. Do not hand-edit.", "",
             f"- Master seed: `{r['master_seed']}` (replay one cycle: `--replay FAULT:CYCLE_SEED`)",
             f"- Sync interval: {r['sync_interval_s']} s", f"- Verdict: **{r['verdict']}**", ""]
    for side, s in r["sides"].items():
        lines += [f"## {side.capitalize()} cycles", "",
                  "| Field | Value |", "|---|---|",
                  f"| Cycles | {s['cycles']} |",
                  f"| Faults injected | {', '.join(f'{k} x{v}' for k, v in s['faults_injected'].items())} |",
                  f"| Records lost (I1) | {s['records_lost']} |",
                  f"| Records duplicated (I2) | {s['records_duplicated']} |",
                  f"| Violations | {json.dumps(s['violations']) if s['violations'] else 'none'} |",
                  f"| Known windows (not violations) | {json.dumps(s['known_windows']) if s['known_windows'] else 'none'} |",
                  f"| Expected failures | {json.dumps(s['expected_fail']) if s['expected_fail'] else 'none'} |",
                  f"| not_mirrored (/sync/status kv) | {s['not_mirrored']} |", ""]
        if s["drain_s"]:
            lines += ["| Fault | Drain cycles | p50 s | max s |", "|---|---|---|---|"]
            lines += [f"| {f} | {d['n']} | {d['p50']} | {d['max']} |" for f, d in s["drain_s"].items()]
            lines.append("")
        if s["stall_skipped_attempts"]:
            lines += [f"Stall observations (skipped drain attempts until a 2xx cleared the latch): "
                      f"{s['stall_skipped_attempts']}", ""]
        for c in s["failing_cycles"]:
            lines.append(f"- FAILING cycle {c['cycle']} ({c['fault']}, seed {c['seed']}): {json.dumps(c['violations'])}")
        if s["failing_cycles"]:
            lines.append("")
    return "\n".join(lines) + "\n"


def write(run_dir: Path) -> dict:
    r = build(run_dir)
    (run_dir / "report.json").write_text(json.dumps(r, indent=2, sort_keys=True) + "\n")
    (run_dir / "report.md").write_text(markdown(r))
    return r


if __name__ == "__main__":
    rep = write(Path(sys.argv[1]))
    print(markdown(rep))
