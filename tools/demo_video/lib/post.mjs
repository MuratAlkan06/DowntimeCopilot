function dialogue(start, end, style, text, layer = 0) {
  return `Dialogue: ${layer},${assTime(start)},${assTime(end)},${style},,0,0,0,,${assText(text)}`;
}

/** The burned subtitle track, in final-cut time. Beat captions at the bottom (a beat may switch caption at a marker),
 *  notices at the top (the opening line over the first beat, the off-screen disclosure, the closing pointer), the
 *  "sped up" label after each labelled cut, and in dry-run footage a DRY RUN mark on every frame. */
export function buildAss({ manifest, mode, timeline, segments, cuts }) {
  const dry = mode === 'dry_run';
  const at = (ms) => outputTime(ms, segments);
  const end = totalS(segments);
  const lines = [];
  timeline.beats.forEach((tb, i) => {
    const mb = manifest.beats.find((b) => b.id === tb.id);
    if (!mb) throw new Error(`timeline beat ${tb.id} is not in beats.json`);
    const bStart = at(tb.start_ms);
    const bEnd = at(tb.end_ms);
    const caps = mb.captions.map((c) => ({ text: (dry && c.text_dry_run) || c.text, from: c.at ? tb.markers?.[c.at] : tb.start_ms }));
    caps.forEach((c, k) => {
      if (c.from == null) throw new Error(`beat ${tb.id}: caption marker ${mb.captions[k].at} was never reached`);
      const until = k + 1 < caps.length ? caps[k + 1].from : tb.end_ms;
      lines.push(dialogue(at(c.from), at(until), 'Caption', c.text));
    });
    if (i === 0) lines.push(dialogue(bStart, bEnd, 'Notice', dry ? manifest.opening.dry_run : manifest.opening.live, 1));
    if (mb.notice) {
      const from = mb.notice.at ? tb.markers?.[mb.notice.at] : tb.start_ms;
      if (from == null) throw new Error(`beat ${tb.id}: notice marker ${mb.notice.at} was never reached`);
      lines.push(dialogue(at(from), bEnd, 'Notice', (dry && mb.notice.text_dry_run) || mb.notice.text, 1));
    }
  });
  for (const c of cuts) {
    if (!c.label) continue;
    const t = at(c.out_ms);
    lines.push(dialogue(t, Math.min(end, t + LABEL_SHOW_S), 'Label', c.label, 2));
  }
  if (dry) lines.push(dialogue(0, end, 'Watermark', manifest.dry_run_mark || 'DRY RUN', 3));
  return `${ASS_HEAD}${lines.join('\n')}\n`;
}

// ---------------------------------------------------------------- ffmpeg commands

const sec = (v) => v.toFixed(3);

/** The MP4 encode: cut by trim+concat, scale, burn captions.ass (resolved from the run directory, the command's
 *  cwd), H.264 for the web, no audio track. */
export function mp4Args({ input = 'raw.webm', ass = 'captions.ass', output, segments, timeline, ptsOffset }) {
  const n = segments.length;
  const parts = [`[0:v]split=${n}${segments.map((_, i) => `[s${i}]`).join('')}`];
  segments.forEach(([a, b], i) => {
    parts.push(`[s${i}]trim=start=${sec(videoTime(a, timeline, ptsOffset))}:end=${sec(videoTime(b, timeline, ptsOffset))},setpts=PTS-STARTPTS[k${i}]`);
  });
  parts.push(`${segments.map((_, i) => `[k${i}]`).join('')}concat=n=${n}:v=1:a=0[cat]`);
  parts.push(`[cat]scale=${VIDEO.width}:${VIDEO.height}:flags=lanczos,setsar=1,subtitles=${ass}[out]`);
  return ['-hide_banner', '-y', '-i', input, '-filter_complex', parts.join(';'), '-map', '[out]', '-an',
    '-c:v', 'libx264', '-preset', 'slow', '-crf', '23', '-maxrate', '850k', '-bufsize', '1700k',
    '-pix_fmt', 'yuv420p', '-movflags', '+faststart', output];
}

/** The GIF: a window of the final MP4 (captions included), 10 fps, 800 px wide with an even height, one palette
 *  per clip tuned to what changes (stats_mode=diff). */
export function gifArgs({ input, output, startS, seconds }) {
  if (seconds > GIF.maxSeconds + 1e-9) throw new Error(`GIF window ${seconds} s is over the ${GIF.maxSeconds} s cap`);
  const graph = `fps=${GIF.fps},scale=${GIF.width}:-2:flags=lanczos,split[a][b];[a]palettegen=stats_mode=diff[p];`
    + '[b][p]paletteuse=dither=bayer:bayer_scale=5:diff_mode=rectangle';
  return ['-hide_banner', '-y', '-ss', sec(startS), '-t', sec(seconds), '-i', input, '-filter_complex', graph, '-loop', '0', output];
}

/** GIF window in final-cut seconds: from a marker of the chosen beat (else its start), at most `seconds` long and
 *  never past the beat's end. */
export function gifWindow({ timeline, segments, beat, from, seconds = GIF.maxSeconds }) {
  const tb = timeline.beats.find((b) => b.id === beat);
  if (!tb) throw new Error(`GIF beat ${beat} is not in the timeline`);
  const fromMs = from ? tb.markers?.[from] : tb.start_ms;
  if (fromMs == null) throw new Error(`GIF marker ${from} was never reached in beat ${beat}`);
  const startS = outputTime(fromMs, segments);
  const len = Math.min(seconds, GIF.maxSeconds, outputTime(tb.end_ms, segments) - startS);
  if (len <= 0) throw new Error(`GIF window for ${beat} is empty`);
  return { startS, seconds: len };
}

// ---------------------------------------------------------------- gates

/** Mechanical gates on the deliverables; returns the violations (empty = pass). */
export function checkGates({ mp4DurationS, mp4Bytes, gifBytes }) {
  const v = [];
  if (!(mp4DurationS >= GATES.minDurationS && mp4DurationS <= GATES.maxDurationS)) {
    v.push(`MP4 duration ${mp4DurationS.toFixed(2)} s is outside ${GATES.minDurationS}-${GATES.maxDurationS} s`);
  }
  if (mp4Bytes > GATES.maxMp4Bytes) v.push(`MP4 is ${mp4Bytes} bytes, over ${GATES.maxMp4Bytes}`);
  if (gifBytes != null && gifBytes > GATES.maxGifBytes) v.push(`GIF is ${gifBytes} bytes, over ${GATES.maxGifBytes}`);
  return v;
}
