"""`make evals`: field-level extraction accuracy per reader and combined, packet faithfulness,
policy grounding rate, latency and cost. Writes RESULTS.md from real runs ONLY.

Exits nonzero, loudly, when there are no fixtures or when DRY_RUN=1 (canned mocks are not models).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IMAGE_EXT = {".jpg": "jpeg", ".jpeg": "jpeg", ".png": "png"}


def loud(msg: str) -> None:
    bar = "!" * 72
    print(f"\n{bar}\nEVALS NOT RUN: {msg}\nRESULTS.md was NOT written. No numbers were produced.\n{bar}\n", file=sys.stderr)


def find_pairs(fixtures: Path) -> list[tuple[Path, Path]]:
    pairs = []
    for img in sorted(fixtures.glob("*")):
        if img.suffix.lower() in IMAGE_EXT and img.with_suffix(".json").exists():
            pairs.append((img, img.with_suffix(".json")))
    return pairs


def _norm(v) -> str | None:
    return None if v is None else " ".join(str(v).lower().split())


def accuracy(predicted: dict, truth: dict) -> tuple[int, int]:
    hits = sum(_norm(predicted.get(k)) == _norm(v) for k, v in truth.items())
    return hits, len(truth)


def pct(hit: int, total: int) -> str:
    return f"{100 * hit / total:.1f}% ({hit}/{total})" if total else "n/a (0 measured)"


def run(fixtures: Path, out: Path) -> int:
    pairs = find_pairs(fixtures)
    if not pairs:
        loud(f"no photographed-form fixtures in {fixtures} (need <name>.jpg|png + <name>.json pairs; "
             "see evals/fixtures/README.md)")
        return 2
    from app import config
    if config.dry_run():
        loud("DRY_RUN=1 would measure canned mocks, not Bedrock/Textract. Run with live credentials and DRY_RUN=0.")
        return 3

    os.environ.setdefault("STORE_PATH", str(Path(tempfile.mkdtemp()) / "evals.sqlite"))
    from app.ai import forms, packets, policy
    from app.capture import textract
    from app.capture.agreement import merge
    from app.rules import snapshot_alerts
    from app.store import get_store
    from contracts import FormType
    from simulator.state import load_patients

    per = {"textract": [0, 0], "bedrock": [0, 0], "combined": [0, 0]}
    for img, gt_path in pairs:
        gt = json.loads(gt_path.read_text())
        ft, truth = FormType(gt["form_type"]), gt["fields"]
        data = img.read_bytes()
        t = textract.read(data, ft)
        b = forms.read_form(data, IMAGE_EXT[img.suffix.lower()], ft, actor_role="evals")
        combined = {f.name: f.value for f in merge(t, b)}
        for name, fields in (("textract", t.fields if t else None), ("bedrock", b.fields), ("combined", combined)):
            if fields is None:
                continue
            h, n = accuracy(fields, truth)
            per[name][0] += h
            per[name][1] += n

    kept = rejected = 0
    for p in load_patients():
        now = p.snapshot_time
        pk = packets.generate_packet(p, snapshot_alerts(p, now), now, actor_role="evals")
        kept += sum(not packets.is_omission(i) for s in packets.SECTIONS for i in getattr(pk.sbar, s))
        m = next((re.search(r"rejected (\d+) line", r) for r in pk.guardrail.reasons if "faithfulness" in r), None)
        rejected += int(m.group(1)) if m else 0

    questions = json.loads((ROOT / "evals" / "questions.json").read_text())
    grounded = sum(policy.ask(q, actor_role="evals").grounded for q in questions)

    calls = get_store().list_costs()
    lat = sorted(c["latency_ms"] for c in calls)
    usd = sum(c["usd"] for c in calls)
    models = sorted({c["model_id"] for c in calls})
    lines = [
        "# RESULTS",
        "",
        f"Generated by `make evals` at {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}. Do not hand-edit.",
        "",
        "## Paths that ran",
        "",
        f"- Models: {', '.join(models)}",
        f"- Textract second read: {'on' if config.textract_enabled() else 'off (single read)'}",
        f"- Guardrail: {config.guardrail_mode()}",
        "",
        "## Numbers",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Form fixtures | {len(pairs)} |",
        f"| Field accuracy, Textract | {pct(*per['textract'])} |",
        f"| Field accuracy, Bedrock vision | {pct(*per['bedrock'])} |",
        f"| Field accuracy, combined (agreement) | {pct(*per['combined'])} |",
        f"| Packet faithfulness (lines with resolvable source_path) | {pct(kept, kept + rejected)} |",
        f"| Policy grounding rate | {pct(grounded, len(questions))} |",
        f"| Model calls | {len(calls)} |",
        f"| Latency p50 / max (ms) | {lat[len(lat) // 2] if lat else 'n/a'} / {lat[-1] if lat else 'n/a'} |",
        f"| Estimated cost (USD, all calls) | {usd:.4f} |",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {out}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--fixtures", type=Path, default=ROOT / "evals" / "fixtures")
    ap.add_argument("--out", type=Path, default=ROOT / "RESULTS.md")
    args = ap.parse_args(argv)
    return run(args.fixtures, args.out)


if __name__ == "__main__":
    raise SystemExit(main())
